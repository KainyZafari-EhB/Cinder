function tokens(s) {
	const rule = (scope, foreground, fontStyle) => ({ scope, settings: fontStyle ? { foreground, fontStyle } : { foreground } });
	return [
		rule(['comment', 'punctuation.definition.comment'], s.comment, 'italic'),
		rule(['keyword', 'storage', 'storage.type', 'keyword.control', 'keyword.operator.new', 'keyword.operator.expression'], s.keyword),
		rule(['string', 'string.template', 'punctuation.definition.string'], s.string),
		rule(['constant.numeric', 'constant.language', 'constant.character', 'support.constant'], s.number),
		rule(['entity.name.function', 'support.function', 'meta.function-call.generic', 'variable.function'], s.fn),
		rule(['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class', 'storage.type.java', 'storage.type.cs'], s.type),
		rule(['variable', 'meta.definition.variable.name', 'support.variable'], s.variable),
		rule(['variable.other.property', 'variable.other.object.property', 'support.type.property-name', 'meta.object-literal.key'], s.property),
		rule(['punctuation', 'meta.brace', 'keyword.operator'], s.punctuation),
		rule(['entity.name.tag', 'meta.tag.sgml'], s.tag),
		rule(['entity.other.attribute-name'], s.string),
		rule(['string.regexp', 'constant.other.character-class.regexp'], s.regex),
		rule(['variable.parameter'], s.variable, 'italic'),
		rule(['markup.heading', 'entity.name.section'], s.keyword, 'bold'),
		rule(['markup.bold'], s.variable, 'bold'),
		rule(['markup.italic'], s.variable, 'italic'),
		rule(['markup.inline.raw', 'markup.fenced_code.block'], s.string),
		rule(['markup.underline.link'], s.fn),
		rule(['invalid', 'invalid.illegal'], s.tag),
	];
}

const out = join(import.meta.dirname, 'themes');
mkdirSync(out, { recursive: true });
for (const [id, palette] of Object.entries(palettes)) {
	const theme = {
		name: palette.label,
		type: palette.type,
		semanticHighlighting: true,
		colors: workbench(palette),
		tokenColors: tokens(palette.syntax),
		semanticTokenColors: {
			'parameter': { foreground: palette.syntax.variable, italic: true },
			'property': palette.syntax.property,
			'type': palette.syntax.type,
			'class': palette.syntax.type,
			'interface': palette.syntax.type,
			'enumMember': palette.syntax.number,
			'function': palette.syntax.fn,
			'method': palette.syntax.fn,
		},
	};
	writeFileSync(join(out, `${id}.json`), JSON.stringify(theme, null, '\t') + '\n');
	console.log(`wrote themes/${id}.json`);
}
